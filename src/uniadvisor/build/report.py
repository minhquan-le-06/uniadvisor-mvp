"""reports/data_report.md: what data the advisor runs on, how good it is, and what is missing.
Regenerated by `uniadvisor report` after every collect/build/backtest."""

from __future__ import annotations

import json
from datetime import date

import pandas as pd

from uniadvisor.paths import COLLECTED, PROCESSED, REPORTS, SLM_DATA


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def build() -> str:
    cut = pd.read_csv(PROCESSED / "cutoffs.csv", dtype=str)
    prog = pd.read_csv(PROCESSED / "programs.csv", dtype=str)
    schools = pd.read_csv(PROCESSED / "schools.csv", dtype=str)
    excl = pd.read_csv(PROCESSED / "schools_excluded.csv", dtype=str)
    probs = pd.read_csv(PROCESSED / "check_problems.csv", dtype=str)
    dmeta = pd.read_csv(PROCESSED / "distributions_meta.csv")
    vne = pd.read_csv(COLLECTED / "vnexpress_cutoffs.csv", dtype=str)
    vnn = pd.read_csv(COLLECTED / "vietnamnet_cutoffs.csv", dtype=str)
    ads_path = COLLECTED / "ads_final_cutoffs.csv"
    ads = pd.read_csv(ads_path, dtype=str) if ads_path.exists() else pd.DataFrame()
    bt = json.loads((REPORTS / "backtest.json").read_text(encoding="utf-8")) if (REPORTS / "backtest.json").exists() else None
    dist_rep = json.loads((REPORTS / "distributions.json").read_text(encoding="utf-8")) if (REPORTS / "distributions.json").exists() else {}
    slm = json.loads((SLM_DATA / "stats.json").read_text(encoding="utf-8")) if (SLM_DATA / "stats.json").exists() else None

    cut["scale"] = cut.scale.astype(int)
    by_year = cut[cut.scale == 30].pivot_table(index="year", columns="status", values="key_code", aggfunc="count", fill_value=0).reset_index()
    tuition_known = prog.tuition_min.notna() & (prog.tuition_imputed == "False")
    exact = dmeta[dmeta.provenance == "exact"]
    exact_years = sorted(exact.year.unique().tolist())
    out = [
        f"# Data report (generated {date.today().isoformat()})",
        "",
        "MVP scope: THPT exam-score method, universities in Hà Nội and TP.HCM, cutoff history 2018-2026 (2023-2026 from news sources), advice for 2027.",
        "",
        "## Sources",
        "",
        "| Source | Trust | What | Rows collected |",
        "|---|---|---|---|",
        f"| VietNamNet cutoff API | 3 (major news) | cutoffs 2023-2026, all methods mixed, method in a free-text note | {len(vnn)} |",
        *([f"| ADS_Final student project (github.com/HTNam1710/ADS_Final, also in mduchd/DSS_Dataset) | 4 (scraped aggregate) | "
           f"THPT cutoffs 2018-2024 per combination; the only source for 2018-2022; names unreliable in some years, scores match "
           f"VietNamNet in ~90% of 2023-2024 rows | {len(ads)} |"] if len(ads) else []),
        f"| VnExpress tra cứu đại học | 3 (major news) | cutoffs 2025-2026 with a THPT column, tuition | {len(vne)} |",
        "| VnExpress phổ điểm 2026 | 3 | per-subject (0.25 bins) and 13 per-combination (1-point bins) score histograms | 2026 only |",
        "| Ministry figures quoted in news (data/manual/distribution_anchors.csv) | 5 (hand-entered, quoted) | 2025 p50/p75/p90 for 7 combinations; 2023-2024 means | 28 |",
        f"| UniPilotData step-1 export | 4 (aggregator) | school details, 2026 programs, quotas, THPT combinations | {len(prog)} programs matched |",
        *([f"| Per-candidate score files in data/inbox/ (not in git; e.g. github.com/sdgedfegw/du-lieu-diem-thi) | 4 (public "
           f"Ministry results, compiled) | exact score distributions per combination | {', '.join(map(str, exact_years))} "
           f"(up to {int(exact.n.max()):,} candidates per combination) |"] if exact_years else []),
        "",
        "## Cutoffs (30-point THPT method)",
        "",
        _md(by_year),
        "",
        "`confirmed_2_sources` = at least two sources agree within 0.05; `disputed` = they differ (preference VnExpress > VietNamNet > "
        "ADS_Final, flagged in the app); `single_source` = only one source has it (2018-2022 always: ADS_Final only). "
        "A history year is dropped, with everything older, when the program name differs from the current one and the cutoff "
        "jumps > 2.5 points (schools reuse program codes).",
        "",
        f"Excluded as not comparable: {int((cut.scale == 40).sum())} rows on a 40-point scale (doubled subject) and "
        f"{int((cut.scale == 100).sum())} rows on 100/150-point combined scales.",
        "",
        "Validation problems: " + ", ".join(f"{k}: {v}" for k, v in probs.groupby("rule").size().items()) + " (see data/processed/check_problems.csv).",
        "",
        "## Scope",
        "",
        f"{len(schools)} schools ({', '.join(f'{c}: {n}' for c, n in schools.city.value_counts().items())}), {len(prog)} programs.",
        "",
        "Programs by years of cutoff history: " + ", ".join(f"{k} năm: {v}" for k, v in prog.years_with_cutoff.value_counts().sort_index().items()) + ".",
        "",
        f"Tuition known from a source for {int(tuition_known.sum())} programs ({tuition_known.mean():.0%}); "
        f"{int(((prog.tuition_imputed == 'True') & prog.tuition_min.notna()).sum())} use their school's median (marked 'ước tính' in the app); "
        f"{int(prog.tuition_min.isna().sum())} unknown.",
        "",
        "Schools dropped: " + ", ".join(excl.school_code) + ". Reason: " + (excl.reason.iloc[0] if len(excl) else "-"),
        "",
        "## Score distributions",
        "",
        _md(dmeta.groupby(["year", "provenance"]).size().rename("combinations").reset_index()),
        "",
        "- `observed`: real 2026 histograms. `synthesized`: 2026 combinations without a published histogram, built from the "
        f"real per-subject histograms (Gaussian copula + selection correction; leave-one-out KS vs observed ≈ "
        f"{dist_rep.get('copula', {}).get('leave_one_out_ks_mean', '?')}). `anchored`/`year_shift`: the 2026 shape moved to "
        "match published percentiles/means (weak).",
        "- `exact`: built from per-candidate score files (data/inbox/). The 2026 file matches VnExpress's per-subject "
        "candidate counts exactly." if exact_years else
        "- The engine only percentile-equates between *trusted* distributions (observed/exact); with today's data that means "
        "no equating across years (see backtest).",
        "",
    ]
    if bt:
        e = bt["engine_pre_results"]["all"]
        c = bt["calibration_cross_fitted"]
        out += [
            "## Backtest (forecast 2025 and 2026 from earlier years)",
            "",
            f"- Cutoff MAE {e['mae']} points (naive 'same as last year': {e['naive_mae']}); within ±1 point: {e['within_1pt']:.0%}.",
            f"- Chosen: equate={bt['chosen']['equate']}, recency={bt['chosen']['recency']}. {bt.get('note', '')}",
            *([f"- Same-percentile equating onto the target year's own distribution: MAE "
               f"{bt['ablation_equate_onto_target_year']['all']['mae']} (vs raw {e['naive_mae']}). It helps mid-range programs "
               "but fails at both ends: selective programs stay sticky in points and low ones sit on the ministry floors."]
              if "ablation_equate_onto_target_year" in bt else []),
            f"- P(admit) calibration (cross-fitted): Brier {c['brier']}, ECE {c['ece']}. By bucket (predicted → actual): "
            + "; ".join(f"{b['bucket']} {b['mean_pred']:.0%} → {b['admit_rate']:.0%}" for b in c["buckets"]) + ".",
            "- Predictions are slightly conservative because cutoffs dropped in the 2025 reform year.",
            "",
        ]
    if slm:
        out += [
            "## SLM training data",
            "",
            f"- {slm['train']['examples']} / {slm['val']['examples']} / {slm['test']['examples']} examples (train/val/test), "
            f"split by university ({slm['schools_per_split']}), synthetic students × real programs × 7 typed questions.",
            "- Labels come from the rubric teacher (5 simulated annotators → soft labels). They are only as good as the "
            "generator's phrase banks: a model trained on them must be checked on the **human gold set** "
            "(data/slm/gold_to_label.csv → gold_labeled.csv) before being trusted, and ideally retrained on LLM-teacher labels "
            "(`uniadvisor slm-relabel`).",
            "",
        ]
    out += [
        "## Known gaps (priority order)",
        "",
        ("1. **A better cutoff model.** Exact distributions did not beat 'same as last year'; the next gains need other "
         "signals (quota history, applicant counts per program, per-combination cutoffs), not better distributions."
         if exact_years else
         "1. **Exact score distributions for 2023-2025.** Per-candidate score files (e.g. github.com/sdgedfegw/du-lieu-diem-thi) "
         "dropped into data/inbox/ replace the approximations and let the backtest test percentile equating on real data."),
        "2. **Quota history.** Only 2026 quotas are known, so the quota adjustment in the forecast is off (kappa = 0).",
        "3. **Tuition** for ~half the programs is a school-level estimate; the đề án (UniPilotData step 6) has the real figures.",
        "4. **Combination-specific cutoffs.** When a program sets different cutoffs per combination, the lowest is kept.",
        "5. **Employment outcomes** are not collected; the 'job/income' priority falls back to selectivity.",
        "6. **Human gold labels** for the SLM do not exist yet (template exported).",
    ]
    text = "\n".join(out) + "\n"
    (REPORTS / "data_report.md").write_text(text, encoding="utf-8")
    return text
